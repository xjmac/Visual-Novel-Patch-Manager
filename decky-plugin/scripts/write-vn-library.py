#!/usr/bin/env python3
"""Write the Decky visual-novel catalog from the bundled VNDB database."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DB_PATH = ROOT / "vndb_steam_database.json"
OUT_PATH = Path(__file__).resolve().parents[1] / "src" / "vnLibrary.generated.ts"
# Civilization V and World of Goo. Ordinary Steam games stay out of the catalog.
EXCLUDED = ("8930", "22000")


def main() -> int:
    database = json.loads(DB_PATH.read_text(encoding="utf-8"))
    titles = {}
    for app_id, entry in database.items():
        if not isinstance(entry, dict):
            continue
        if not entry.get("is_vn") or not entry.get("has_18plus_en_patch"):
            continue
        title = str(entry.get("vn_title") or "").strip()
        if not title:
            continue
        titles[str(app_id)] = title
    for app_id in EXCLUDED:
        if app_id in titles:
            print(f"{app_id} is not a visual novel and must stay out of the library", file=sys.stderr)
            return 1
    if len(titles) < 100:
        print("visual novel catalog is unexpectedly small", file=sys.stderr)
        return 1
    body = (
        "// Generated by scripts/write-vn-library.py from vndb_steam_database.json.\n"
        "// Steam app id to title for visual novels that have an English 18+ patch.\n"
        "export const vnTitles: Record<string, string> = " + json.dumps(titles, ensure_ascii=False) + ";\n"
    )
    OUT_PATH.write_text(body, encoding="utf-8")
    print(f"wrote {len(titles)} visual novels")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
